#!/usr/bin/env python3
"""Benchmark one producer-owned SENS compiler stage on CPU vs CUDA.

The semantic input is generated by the pinned SENS producer. This harness
owns only transport parsing, batching, measurement and evidence collection.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import platform
import shutil
import statistics
import subprocess
import sys
import tempfile
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
PROGRAM = ROOT / "futhark" / "compiler_legality_scan.fut"
PARSER = ROOT / "host"
EXPECTED_SENS = "1869fd5e51f38565ca968abceaa4bc933ae7a114"
DEFAULT_SIZES = [4096, 65536, 1048576, 4194304]


def run(cmd, *, cwd=None, env=None, capture=False, check=True):
    p = subprocess.run(
        [str(x) for x in cmd],
        cwd=cwd,
        env=env,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )
    if check and p.returncode != 0:
        stdout = p.stdout or ""
        stderr = p.stderr or ""
        raise SystemExit(
            f"command failed ({p.returncode}): {' '.join(map(str, cmd))}\n"
            + stdout
            + stderr
        )
    return p


def cargo() -> str:
    resolved = shutil.which("cargo")
    if resolved:
        return resolved
    fallback = Path.home() / ".cargo" / "bin" / "cargo"
    if fallback.is_file():
        return str(fallback)
    raise SystemExit("cargo is required for the pinned SENS producer")


def futhark(explicit: str | None) -> Path:
    candidates = []
    if explicit:
        candidates.append(Path(explicit))
    candidates.append(ROOT / ".tools" / "bin" / "futhark")
    found = shutil.which("futhark")
    if found:
        candidates.append(Path(found))
    for candidate in candidates:
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return candidate.resolve()
    raise SystemExit("Futhark compiler not found; run make bootstrap first")


def cuda_env(base: dict[str, str]) -> dict[str, str]:
    env = dict(base)
    root = Path(env.get("CUDA_HOME") or env.get("CUDA_PATH") or "/usr/local/cuda-12.6")
    target = root / "targets" / "x86_64-linux"
    driver = Path("/usr/lib/wsl/lib")
    env["CUDA_HOME"] = str(root)
    env["CUDA_PATH"] = str(root)
    for key, values in {
        "CPATH": [str(target / "include")],
        "LIBRARY_PATH": [str(driver), str(target / "lib")],
        "LD_LIBRARY_PATH": [str(driver), str(target / "lib")],
    }.items():
        current = env.get(key)
        env[key] = ":".join(values + ([current] if current else []))
    return env


def producer_artifacts(sens_root: Path) -> list[dict[str, str]]:
    result = run(
        [
            cargo(),
            "run",
            "--quiet",
            "-p",
            "xtask",
            "--",
            "compiler-export",
            "--artifact",
        ],
        cwd=sens_root,
        capture=True,
    )
    text = result.stdout.strip()
    artifacts = [
        chunk.strip()
        for chunk in text.split("\n\n")
        if chunk.strip().startswith("(compilation-artifact")
    ]
    if len(artifacts) != 9:
        raise SystemExit(f"expected 9 SENS compiler artifacts, got {len(artifacts)}")

    sys.path.insert(0, str(PARSER))
    from sens_compiler_request import SensRequestError, load_sens_artifact

    with tempfile.TemporaryDirectory() as tmp:
        parsed: list[dict[str, str]] = []
        for index, source in enumerate(artifacts):
            path = Path(tmp) / f"artifact-{index}.lisp"
            path.write_text(source + "\n", encoding="utf-8")
            try:
                artifact = load_sens_artifact(path)
            except SensRequestError as exc:
                raise SystemExit(f"producer artifact {index} rejected: {exc}") from exc
            semantic_request = artifact["semantic_request"]
            if not isinstance(semantic_request, str):
                raise SystemExit(f"producer artifact {index} has invalid embedded request")
            parsed.append(
                {
                    "fixture_id": artifact["fixture_id"],
                    "semantic_request_sha256": artifact["semantic_request_sha256"],
                    "semantic_request": semantic_request,
                    "artifact_source": source,
                }
            )
    return parsed


def parse_requests(artifacts: list[dict[str, str]]) -> tuple[list[int], list[int], list[int], dict]:
    sys.path.insert(0, str(PARSER))
    from sens_compiler_request import (  # type: ignore
        EXPECTED_SOURCE_COMMIT,
        SENS_ROLE_TO_BACKEND_ROLE,
        SensRequestError,
        load_sens_request,
    )

    inverse = {
        role: index
        for index, role in enumerate(SENS_ROLE_TO_BACKEND_ROLE.values())
    }
    domains: list[int] = []
    bits: list[int] = []
    roles: list[int] = []
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for index, artifact in enumerate(artifacts):
            source = artifact["semantic_request"]
            path = Path(tmp) / f"request-{index}.lisp"
            path.write_text(source + "\n", encoding="utf-8")
            try:
                parsed = load_sens_request(path)
            except SensRequestError as exc:
                raise SystemExit(f"producer request {index} rejected: {exc}") from exc
            domain = int(parsed["identity"]["domain"][1:])
            value = int(parsed["identity"]["bits"], 2)
            role_name = parsed["role"]
            role_code = inverse[role_name]
            domains.append(domain)
            bits.append(value)
            roles.append(role_code)
            rows.append(
                {
                    "fixture_id": parsed["fixture_id"],
                    "domain": domain,
                    "bits": parsed["identity"]["bits"],
                    "role": role_name,
                    "role_code": role_code,
                    "source_commit": parsed["provenance"]["source_commit"],
                    "authority_sha256": parsed["provenance"]["role_authority_digest"],
                    "semantic_request_sha256": artifact["semantic_request_sha256"],
                }
            )

    if any(row["source_commit"] != EXPECTED_SENS for row in rows):
        raise SystemExit("producer output is not from the pinned SENS authority")
    authority = {row["authority_sha256"] for row in rows}
    if len(authority) != 1:
        raise SystemExit("producer requests disagree on role-authority digest")
    digests = {row["semantic_request_sha256"] for row in rows}
    if len(digests) != len(rows):
        raise SystemExit("producer artifacts are not byte-distinct by semantic-request-sha256")
    return domains, bits, roles, {
        "source_commit": EXPECTED_SENS,
        "role_authority_digest": next(iter(authority)),
        "semantic_request_sha256": sorted(digests),
        "rows": rows,
    }


def bench(
    fk: Path,
    backend: str,
    spec: Path,
    out_json: Path,
    env: dict[str, str],
    runs: int,
    profile: bool = False,
):
    command = [
        fk,
        "bench",
        PROGRAM,
        f"--backend={backend}",
        f"--spec-file={spec}",
        f"--runs={runs}",
        "--no-convergence-phase",
        f"--json={out_json}",
    ]
    if profile:
        command.append("--profile")
    run(command, env=env)


def build_transfer_probe(fk: Path, out: Path, env: dict[str, str]) -> Path:
    libbase = out / "compiler_legality_scan_cuda"
    run(
        [fk, "cuda", "--library", PROGRAM, "-o", libbase],
        env=env,
    )
    root = Path(env.get("CUDA_HOME") or env.get("CUDA_PATH") or "/usr/local/cuda-12.6")
    target = root / "targets" / "x86_64-linux"
    driver = Path("/usr/lib/wsl/lib")
    binary = out / "compiler_slice_transfer_probe"
    run(
        [
            "cc",
            "-O2",
            "-std=c99",
            "-Wall",
            "-Wextra",
            "-I",
            out,
            "-I",
            target / "include",
            ROOT / "bench" / "compiler_slice_transfer_probe.c",
            Path(str(libbase) + ".c"),
            "-o",
            binary,
            "-L",
            driver,
            "-L",
            target / "lib",
            "-lcuda",
            "-lcudart",
            "-lnvrtc",
            "-lm",
            "-pthread",
            "-ldl",
        ],
        env=env,
    )
    return binary


def run_transfer_probe(
    binary: Path,
    seed_path: Path,
    sizes: list[int],
    repeats: int,
    env: dict[str, str],
    out: Path,
) -> list[dict]:
    rows: list[dict] = []
    raw_path = out / "transfer_raw.csv"
    with raw_path.open("w", encoding="utf-8") as raw:
        for size in sizes:
            result = run(
                [binary, seed_path, size, repeats],
                env=env,
                capture=True,
            )
            raw.write(result.stdout)
            records = [
                line for line in result.stdout.splitlines()
                if line and not line.startswith("batch,")
            ]
            for line in records:
                fields = line.split(",")
                if len(fields) != 7:
                    raise SystemExit(f"invalid transfer probe row: {line}")
                rows.append(
                    {
                        "batch": int(fields[0]),
                        "repeat": int(fields[1]),
                        "h2d_import_bytes": int(fields[2]),
                        "d2h_export_bytes": int(fields[3]),
                        "h2d_import_ns": int(fields[4]),
                        "kernel_ns": int(fields[5]),
                        "d2h_export_ns": int(fields[6]),
                    }
                )

    summaries = []
    for size in sizes:
        subset = [row for row in rows if row["batch"] == size]
        if len(subset) != repeats:
            raise SystemExit(
                f"expected {repeats} transfer rows for {size}, got {len(subset)}"
            )
        h2d = statistics.median([row["h2d_import_ns"] for row in subset])
        kernel = statistics.median([row["kernel_ns"] for row in subset])
        d2h = statistics.median([row["d2h_export_ns"] for row in subset])
        summaries.append(
            {
                "elements": size,
                "h2d_import_bytes": subset[0]["h2d_import_bytes"],
                "d2h_export_bytes": subset[0]["d2h_export_bytes"],
                "resident_payload_bytes": (
                    subset[0]["h2d_import_bytes"] + subset[0]["d2h_export_bytes"]
                ),
                "h2d_import_median_us": h2d / 1000.0,
                "kernel_median_us": kernel / 1000.0,
                "d2h_export_median_us": d2h / 1000.0,
                "phase_sum_median_us": (h2d + kernel + d2h) / 1000.0,
            }
        )
    (out / "transfer_summary.json").write_text(
        json.dumps({"schema": 1, "rows": summaries}, indent=2) + "\n",
        encoding="utf-8",
    )
    return summaries


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--futhark")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--sizes", default=",".join(map(str, DEFAULT_SIZES)))
    ap.add_argument("--runs", type=int, default=5)
    args = ap.parse_args()

    sizes = [int(x) for x in args.sizes.split(",") if x]
    if not sizes or any(n <= 0 for n in sizes):
        raise SystemExit("sizes must be positive")
    if args.runs <= 0:
        raise SystemExit("runs must be positive")

    sens_root = ROOT / "vendor" / "sens"
    if not (sens_root / "Cargo.toml").is_file():
        raise SystemExit("vendor/sens is missing; run make sens-fetch first")

    fk = futhark(args.futhark)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = (args.out or ROOT / "bench" / "results" / f"compiler-slice-{stamp}").resolve()
    out.mkdir(parents=True, exist_ok=True)

    artifacts = producer_artifacts(sens_root)
    domains, bits, roles, provenance = parse_requests(artifacts)

    (out / "producer_artifacts.lisp").write_text(
        "\n\n".join(artifact["artifact_source"] for artifact in artifacts) + "\n",
        encoding="utf-8",
    )


    spec = out / "compiler-slice.spec"
    seed_domains = ", ".join(map(str, domains))
    seed_bits = ", ".join(map(str, bits))
    seed_roles = ", ".join(map(str, roles))
    lines: list[str] = ["==", "entry: compiler_legality_scan"]
    for size in sizes:
        lines.append(
            f'"compiler-slice-{size}" input {{ [{seed_domains}] [{seed_bits}] {size}i64 }}'
        )
        lines.append(f"output {{ [{size}i64] }}")
    spec.write_text("\n".join(lines) + "\n", encoding="utf-8")

    base_env = dict(os.environ)
    gpu_env = cuda_env(base_env)
    c_json = out / "c.json"
    cuda_json = out / "cuda.json"
    bench(fk, "c", spec, c_json, base_env, args.runs)
    bench(fk, "cuda", spec, cuda_json, gpu_env, args.runs, profile=True)

    c_data = json.loads(c_json.read_text(encoding="utf-8"))
    g_data = json.loads(cuda_json.read_text(encoding="utf-8"))
    csets = next(iter(c_data.values()))["datasets"]
    gsets = next(iter(g_data.values()))["datasets"]
    summary = []
    for size in sizes:
        key = f"compiler-slice-{size}"
        if key not in csets or key not in gsets:
            raise SystemExit(f"missing benchmark dataset for {size}")
        cmed = statistics.median(csets[key]["runtimes"])
        gmed = statistics.median(gsets[key]["runtimes"])
        events = gsets[key].get("profiling", {}).get("events", [])
        kernel_us = events[0].get("duration") if events else None
        summary.append(
            {
                "elements": size,
                "c_median_us": cmed,
                "cuda_median_us": gmed,
                "cuda_over_c_speedup": cmed / gmed,
                "cuda_kernel_us": kernel_us,
            }
        )

    seed_path = out / "producer_seed.txt"
    seed_path.write_text(
        " ".join(map(str, domains)) + "\n"
        + " ".join(map(str, bits)) + "\n",
        encoding="utf-8",
    )
    transfer_probe = build_transfer_probe(fk, out, gpu_env)
    transfer_summary = run_transfer_probe(
        transfer_probe,
        seed_path,
        sizes,
        args.runs,
        gpu_env,
        out,
    )

    nvidia_list = run(
        ["nvidia-smi", "-L"],
        env=gpu_env,
        capture=True,
        check=False,
    ).stdout.strip()
    nvidia_query = run(
        [
            "nvidia-smi",
            "--query-gpu=name,compute_cap,driver_version",
            "--format=csv,noheader",
        ],
        env=gpu_env,
        capture=True,
        check=False,
    ).stdout.strip()

    metadata = {
        "schema": 1,
        "timestamp_utc": stamp,
        "program": str(PROGRAM.relative_to(ROOT)),
        "git": run(["git", "-C", ROOT, "rev-parse", "HEAD"], capture=True).stdout.strip(),
        "futhark": run([fk, "--version"], capture=True).stdout.strip(),
        "platform": platform.platform(),
        "nvidia_smi_list": nvidia_list,
        "nvidia_smi_query": nvidia_query,
        "sizes": sizes,
        "runs": args.runs,
        "producer": {
            "repository": "juv4uk/sens",
            "commit": provenance["source_commit"],
            "artifact_schema": "compiler-compilation-artifact/1",
            "role_authority_digest": provenance["role_authority_digest"],
            "semantic_request_sha256": provenance["semantic_request_sha256"],
            "rows": provenance["rows"],
        },
        "source_request_bytes": sum(
            len(artifact["semantic_request"].encode("utf-8")) for artifact in artifacts
        ),
        "seed_request_bytes": len(domains) * 3 * 4,
        "resident_payload_bytes": len(domains) * 3 * 4 + 8,
        "entry": "compiler_legality_scan",
        "raw": {"c": "c.json", "cuda": "cuda.json", "transfer": "transfer_raw.csv"},
        "summary": summary,
        "transfer_summary": transfer_summary,
        "note": (
            "Batch items are deterministic repetitions of nine distinct "
            "producer-derived compiler-semantic requests; this is a mechanical "
            "throughput experiment, not semantic expansion by Futhark. "
            "The seed request bytes are imported once; batch expansion and "
            "legality scanning happen on-device."
        ),
    }
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
